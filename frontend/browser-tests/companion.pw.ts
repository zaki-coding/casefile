import { expect, test, type APIRequestContext, type Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

async function openSave(request: APIRequestContext, caseId: string, detectiveId: string) {
  const response = await request.post('/api/investigations', { data: { caseId, detectiveId } })
  await expect(response).toBeOK()
  return (await response.json()).id as string
}

test.beforeAll(async ({ request }, info) => {
  await mkdir(info.project.outputDir, { recursive: true })
  const profile = await (await request.get('/api/profile')).json()
  if (profile.points >= 150) return
  const cases = [
    { caseId: '001', suspect: 'mara', method: 'switch', motive: 'protect', evidence: ['badge', 'treatment', 'relay'] },
    { caseId: '002', suspect: 'sabine', method: 'bypass', evidence: ['route', 'latch'] },
  ]
  for (const { caseId, ...accusation } of cases) {
    const id = await openSave(request, caseId, 'adrian')
    for (const file of accusation.evidence) await expect(await request.post(`/api/investigations/${id}/evidence/${file}`)).toBeOK()
    await expect(await request.post(`/api/investigations/${id}/accusation`, { data: accusation })).toBeOK()
  }
})

const companion = (page: Page) => page.getByRole('complementary', { name: 'Detective companion' })
const line = (page: Page) => companion(page).getByRole('status')
const room = (page: Page, name: string) => page.getByRole('navigation', { name: 'Investigation rooms' }).getByRole('link', { name })
const file = (page: Page, name: string) => page.getByRole('article', { name, exact: true })

async function checkLayout(page: Page) {
  const content = page.locator('.page-scroll')
  const view = await content.boundingBox()
  const dock = await companion(page).boundingBox()
  expect(view!.y + view!.height).toBeLessThanOrEqual(dock!.y + 1)
  expect(dock!.y + dock!.height).toBeLessThanOrEqual(page.viewportSize()!.height + 1)
  expect(await content.evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(1)
  expect(await companion(page).evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(1)
}

test('a new case reacts only to saved actions, through a reviewed accusation and verdict', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('link', { name: /New Investigation/ }).click()
  await page.getByRole('button', { name: 'Select Adrian Cross' }).click()
  await page.getByRole('button', { name: /YES.*Confirm Detective/ }).click()
  await page.getByRole('link', { name: /Read Case 001 Briefing/ }).click()
  await expect(companion(page)).toHaveCount(0)
  await page.getByRole('button', { name: 'Begin Investigation' }).click()
  await expect(line(page)).toContainText('put a time to')
  const relay = file(page, 'Relay event log')
  await page.route('**/evidence/relay', route => route.fulfill({ status: 409, json: { detail: 'File unavailable.' } }), { times: 1 })
  await relay.getByRole('button').click()
  await expect(page.getByRole('alert')).toHaveText('File unavailable.')
  await expect(line(page)).toContainText('put a time to')
  let release!: () => void
  const waitForServer = new Promise<void>(done => { release = done })
  await page.route('**/evidence/relay', async route => { await waitForServer; await route.continue() }, { times: 1 })
  await relay.getByRole('button').click()
  await expect(relay.getByRole('button')).toBeDisabled()
  await expect(line(page)).toContainText('put a time to')
  release()
  await expect(line(page)).toContainText('clock to work from')
  await relay.getByRole('button', { name: /Fold file/ }).click()
  await relay.getByRole('button', { name: /Read pinned file/ }).click()
  await expect(line(page)).toContainText('clock to work from')
  await file(page, 'Badge access report').getByRole('button').click()
  await expect(line(page)).toContainText('Who was carrying it?')
  await file(page, 'Rejected treatment request').getByRole('button').click()
  await expect(line(page)).toContainText('request and the reply')
  await room(page, 'Suspect Interviews').click()
  await expect(line(page)).toContainText('request and the reply')
  const alibi = page.getByRole('button', { name: /^Where were you at midnight/ })
  await page.route('**/interviews', route => route.fulfill({ status: 409, json: { detail: 'Answer was not recorded.' } }), { times: 1 })
  await alibi.click()
  await expect(page.getByRole('alert')).toHaveText('Answer was not recorded.')
  await expect(line(page)).toContainText('request and the reply')
  await alibi.click()
  await expect(line(page)).toContainText('place Mara Vale there independently')
  await companion(page).getByRole('button').click()
  await companion(page).getByRole('link', { name: 'View Insight' }).click()
  const ability = page.getByRole('complementary', { name: 'Detective ability' })
  await expect(ability).toBeFocused()
  const insight = ability.getByRole('button', { name: 'Use Insight' })
  await page.route('**/ability', route => route.fulfill({ status: 409, json: { detail: 'Ability was not recorded.' } }), { times: 1 })
  await insight.click()
  await expect(page.getByRole('alert')).toHaveText('Ability was not recorded.')
  await expect(line(page)).toContainText('place Mara Vale there independently')
  await insight.click()
  await expect(line(page)).toContainText('written down the connection')
  await room(page, 'Accusation').click()
  await expect(line(page)).toContainText('trace each claim to a file')
  await page.getByLabel('Culprit', { exact: true }).selectOption('mara')
  await page.getByLabel('Motive', { exact: true }).selectOption('protect')
  await page.getByLabel('Method', { exact: true }).selectOption('switch')
  for (const [claim, id] of [['Identity', 'badge'], ['Motive', 'treatment'], ['Method', 'relay']]) {
    await page.getByLabel(claim + ' evidence', { exact: true }).selectOption(id)
  }
  await page.getByRole('button', { name: 'Review accusation' }).click()
  await expect(page.getByRole('heading', { name: 'Review your accusation' })).toBeVisible()
  const submit = page.getByRole('button', { name: 'Submit accusation' })
  await submit.scrollIntoViewIfNeeded()
  await checkLayout(page)
  const button = await submit.boundingBox()
  expect(button!.y + button!.height).toBeLessThanOrEqual((await companion(page).boundingBox())!.y)
  await submit.click()
  await expect(page.getByRole('heading', { name: 'Case Solved' })).toBeVisible()
  await expect(line(page)).toContainText('sequence holds')
  await page.reload()
  await expect(line(page)).toContainText('sequence holds')
})

for (const [id, name] of [['adrian', 'Adrian Cross'], ['selena', 'Selena Voss'], ['elias', 'Elias Mercer']]) {
  test(`resumes ${name}’s portrait and keeps the dock across rooms`, async ({ page, request }) => {
    const save = await openSave(request, '002', id)
    await expect(await request.put('/api/profile/detective', { data: { detectiveId: id === 'adrian' ? 'elias' : 'adrian' } })).toBeOK()
    await page.goto('/#/career')
    const portrait = await page.getByRole('img', { name, exact: true }).getAttribute('src')
    await page.goto('/#/continue')
    await page.getByRole('link', { name: new RegExp(save.slice(0, 8), 'i') }).click()
    const dock = companion(page)
    const toggle = dock.getByRole('button')
    const shortcuts = dock.getByRole('navigation', { name: 'Detective shortcuts' })
    await expect(dock.getByRole('img', { name })).toHaveAttribute('src', portrait!)
    await expect(shortcuts).toBeHidden()
    await toggle.focus()
    await page.keyboard.press('Enter')
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    await page.keyboard.press('Tab')
    await expect(shortcuts.getByRole('link', { name: 'Evidence board' })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(toggle).toBeFocused()
    await expect(shortcuts).toBeHidden()
    await toggle.click()
    for (const screen of ['Suspect Interviews', 'Detective Equipment', 'Accusation', 'Evidence Board']) {
      await room(page, screen).click()
      await expect(toggle).toHaveAttribute('aria-expanded', 'true')
      await expect(dock.getByRole('img', { name })).toHaveAttribute('src', portrait!)
      await checkLayout(page)
    }
    await page.reload()
    await expect(dock.getByRole('img', { name })).toHaveAttribute('src', portrait!)
    await expect(shortcuts).toBeHidden()
  })
}

test('Pressure follows the interview restrictions and an unsuccessful verdict stays on file', async ({ page, request }) => {
  const id = await openSave(request, '002', 'selena')
  await page.goto(`/#/investigations/${id}/interviews`)
  const pressure = page.getByRole('button', { name: 'Apply Pressure' })
  await expect(pressure).toBeDisabled()
  await page.getByRole('button', { name: /^Where were you when the recorder/ }).click()
  await expect(line(page)).toContainText('verify where Ivo Rusk was')
  await expect(pressure).toBeDisabled()
  await room(page, 'Evidence Board').click()
  await file(page, 'Carrier drum trace').getByRole('button').click()
  await file(page, 'Selector jaw impression').getByRole('button').click()
  await companion(page).getByRole('button').click()
  await companion(page).getByRole('link', { name: 'View Pressure' }).click()
  await expect(pressure).toBeEnabled()
  await pressure.click()
  await expect(line(page)).toContainText('Now I have a follow-up')
  await room(page, 'Accusation').click()
  await page.getByLabel('Suspect', { exact: true }).selectOption('ivo')
  await page.getByLabel('Method', { exact: true }).selectOption('hatch')
  await page.getByRole('checkbox').nth(0).check()
  await page.getByRole('checkbox').nth(1).check()
  await page.getByRole('button', { name: /Submit accusation/ }).click()
  await expect(page.getByRole('heading', { name: 'Case Unsolved' })).toBeVisible()
  await expect(line(page)).toContainText('break under questioning')
  await page.reload()
  await expect(line(page)).toContainText('break under questioning')
})

test('Deep Analysis uses an examined file and compact controls fit with large text and reduced motion', async ({ page, request }) => {
  const id = await openSave(request, '001', 'elias')
  await page.setViewportSize({ width: 320, height: 568 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#/settings')
  await page.getByLabel('Reading size').selectOption('large')
  await page.goto(`/#/investigations/${id}/evidence`)
  await file(page, 'Relay event log').getByRole('button').click()
  const dock = companion(page)
  await dock.getByRole('button').click()
  await checkLayout(page)
  await expect(page.locator('main')).toHaveCSS('animation-name', 'none')
  await expect(dock.getByRole('navigation')).toHaveCSS('animation-name', 'none')
  await dock.getByRole('link', { name: 'View Deep Analysis' }).click()
  const analyze = page.getByRole('button', { name: 'Run Deep Analysis' })
  await expect(analyze).toBeDisabled()
  await page.getByLabel('Evidence for analysis').selectOption('relay')
  await analyze.click()
  await expect(line(page)).toContainText('added my reading')
  await page.reload()
  await expect(dock.getByRole('img', { name: 'Elias Mercer' })).toBeVisible()
  await expect(analyze).toHaveCount(0)
  await page.setViewportSize({ width: 568, height: 320 })
  await dock.getByRole('button').click()
  await checkLayout(page)
})
